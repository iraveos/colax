#[test]
fn create_unlock_crud_lock_reunlock() {
    let mut vault = fast(temp_storage("crud"));
    assert!(!vault.exists());
    vault.create(Some(MASTER)).unwrap();
    assert!(vault.exists());

    let item = vault
        .add_item(&json!({
            "title": "GitHub",
            "username": "me@example.com",
            "password": "example-value",
            "url": "github.com",
        }))
        .unwrap();
    assert_eq!(
        item.url, "https://github.com",
        "bare hostnames get a scheme"
    );

    vault
        .update_item(&item.id, &json!({ "password": "new-password" }))
        .unwrap();
    vault
        .update_item(&item.id, &json!({ "favorite": true }))
        .unwrap();

    vault.lock();
    assert!(!vault.is_unlocked());
    assert!(vault.items().is_none(), "no plaintext while locked");

    assert!(!vault.unlock("wrong password").unwrap());
    assert!(vault.unlock(MASTER).unwrap());
    let items = vault.items().unwrap().to_vec();
    assert_eq!(items.len(), 1);
    assert_eq!(items[0].password, "new-password");
    assert!(items[0].favorite);

    vault.delete_item(&item.id).unwrap();
    assert!(vault.items().unwrap().is_empty());
}

