#[test]
fn restore_rejects_a_wrong_password_and_foreign_files() {
    let mut source = fast(temp_storage("backup-protected"));
    source.create(Some(MASTER)).unwrap();
    source
        .add_item(&json!({ "title": "Locked", "password": "alpha" }))
        .unwrap();
    let backup = source.export_backup().unwrap();

    let mut target = fast(temp_storage("backup-protected-target"));
    let err = target
        .restore_backup(&backup, Some("wrong"), None)
        .unwrap_err();
    assert!(matches!(err, VaultError::Auth), "got {err:?}");
    assert!(!target.exists(), "failed restore must not install a vault");

    // A file that is not an aegis backup at all.
    let mut foreign = backup.clone();
    foreign.format = "something-else".into();
    let err = target
        .restore_backup(&foreign, Some(MASTER), None)
        .unwrap_err();
    assert!(matches!(err, VaultError::NotABackup), "got {err:?}");

    // parse_backup mirrors backup.ts' three checks.
    assert_eq!(
        parse_backup("{ nope").unwrap_err().to_string(),
        "That file is not valid JSON."
    );
    assert_eq!(
        parse_backup("[1,2]").unwrap_err().to_string(),
        "That file is not a vault backup."
    );
    assert_eq!(
        parse_backup(r#"{"format":"nope"}"#)
            .unwrap_err()
            .to_string(),
        "That file is not a Colax vault backup."
    );
    assert_eq!(
        parse_backup(r#"{"format":"aegis-vault-backup"}"#)
            .unwrap_err()
            .to_string(),
        "The backup file is incomplete."
    );
}

/* ---- Cross-compatibility with the TypeScript app ------------------------ */

#[test]
fn restores_a_backup_written_by_the_typescript_app() {
    // Produced by `scripts/make-ts-fixture.mjs` against the real TS
    // VaultService: 600k-iteration PBKDF2, WebCrypto AES-GCM.
    let text = include_str!("fixtures/ts-vault-backup.json");
    let backup = parse_backup(text).unwrap();
    assert_eq!(backup.format, BACKUP_FORMAT);
    assert_eq!(backup.header.iterations, Some(600_000));
    assert!(verify_backup_password(&backup, Some(MASTER)));
    assert!(!verify_backup_password(&backup, Some("nope")));

    let mut vault = fast(temp_storage("ts-fixture"));
    vault.restore_backup(&backup, Some(MASTER), None).unwrap();
    let items = vault.items().unwrap();
    assert_eq!(items.len(), 2);

    let by_title: Vec<_> = items.to_vec();
    let github = by_title
        .iter()
        .find(|i| i.title == "GitHub")
        .expect("GitHub login");
    assert_eq!(github.username, "me@example.com");
    assert_eq!(github.password, "fixture-value-one");
    assert_eq!(github.url, "https://github.com");
    assert_eq!(github.notes, "work account");

    let unicode = by_title
        .iter()
        .find(|i| i.title.starts_with("Bänk"))
        .expect("unicode login");
    assert_eq!(unicode.title, "Bänk 日本語 🔐");
    assert_eq!(unicode.password, "fixture-ünïcode-値-🔐");
    assert_eq!(unicode.username, "björn@example.se");
    assert_eq!(unicode.tags, vec!["finance"]);
    assert!(unicode.favorite);
    assert!(unicode.notes.contains("✨"));

    // And a backup exported from here must parse as a TS backup too.
    let round = serialize_backup(&vault.export_backup().unwrap()).unwrap();
    assert!(round.contains(r#""format": "aegis-vault-backup""#));
    let parsed = parse_backup(&round).unwrap();
    assert_eq!(parsed.items.len(), 2);
}

