#[test]
fn replace_items_acts_as_undo() {
    let mut vault = fast(temp_storage("undo"));
    vault.create(Some(MASTER)).unwrap();
    let a = vault.add_item(&json!({ "title": "A" })).unwrap();
    let b = vault.add_item(&json!({ "title": "B" })).unwrap();

    // Undo of "add B": the set is back to just A.
    vault.replace_items(vec![a.clone()]).unwrap();
    let titles: Vec<String> = vault
        .items()
        .unwrap()
        .iter()
        .map(|i| i.title.clone())
        .collect();
    assert_eq!(titles, vec!["A"]);
    // B's record is gone from disk too.
    let doc = vault.export_backup().unwrap();
    assert_eq!(doc.items.len(), 1);
    assert_ne!(doc.items[0].id, b.id);
}

