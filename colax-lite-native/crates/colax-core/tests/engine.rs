#[test]
fn update_stamps_only_the_fields_that_changed() {
    let mut vault = fast(temp_storage("timestamps"));
    vault.create(Some(MASTER)).unwrap();
    let item = vault
        .add_item(&json!({ "title": "Bank", "password": "old", "username": "before@example.com" }))
        .unwrap();
    thread::sleep(Duration::from_millis(20));

    // A flag flip must not move updatedAt: the staleness scan reads it.
    vault.set_attention(item.id.as_str(), true).unwrap();
    let after_flag = vault.items().unwrap()[0].clone();
    assert!(after_flag.needs_attention);
    assert_eq!(
        after_flag.updated_at, item.updated_at,
        "flags bypass the stamp"
    );

    thread::sleep(Duration::from_millis(20));
    vault
        .update_item(&item.id, &json!({ "favorite": true }))
        .unwrap();
    let after_favourite = vault.items().unwrap()[0].clone();
    assert!(after_favourite.favorite);
    assert!(
        after_favourite.updated_at > item.updated_at,
        "plain updates stamp"
    );
    assert_eq!(
        after_favourite.password_updated_at, item.password_updated_at,
        "untouched password keeps its old change time"
    );

    thread::sleep(Duration::from_millis(20));
    vault
        .update_item(&item.id, &json!({ "password": "new" }))
        .unwrap();
    let after_password = vault.items().unwrap()[0].clone();
    assert!(after_password.password_updated_at >= after_favourite.updated_at);
    assert_eq!(
        after_password.username_updated_at, item.username_updated_at,
        "username untouched"
    );
}

