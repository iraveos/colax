#[test]
fn corrupt_records_are_skipped_instead_of_blocking_unlock() {
    let storage = temp_storage("corrupt-record");
    let mut vault = fast(storage.clone());
    vault.create(Some(MASTER)).unwrap();
    let keep = vault
        .add_item(&json!({ "title": "Good", "password": "x" }))
        .unwrap();

    // Inject a record that will not decrypt, as the TS test did.
    let mut doc = storage.load().unwrap().unwrap();
    doc.items.push(StoredItem {
        id: "broken".into(),
        blob: colax_core::SealedBlob {
            iv: "AAAAAAAAAAAAAAAA".into(), // 12 zero bytes
            ct: "AAAA".into(),
        },
        updated_at: 0,
    });
    storage.save(&doc).unwrap();

    vault.lock();
    assert!(vault.unlock(MASTER).unwrap());
    let ids: Vec<String> = vault
        .items()
        .unwrap()
        .iter()
        .map(|i| i.id.clone())
        .collect();
    assert_eq!(ids, vec![keep.id], "only the good record survives");
}

