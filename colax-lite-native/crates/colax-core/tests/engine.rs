#[test]
fn backup_export_verify_restore_preserves_every_item() {
    let mut source = fast(temp_storage("backup-source"));
    source.create(Some(MASTER)).unwrap();
    source
        .add_item(&json!({ "title": "One", "password": "alpha" }))
        .unwrap();
    source
        .add_item(&json!({ "title": "Two", "password": "beta" }))
        .unwrap();

    let backup = source.export_backup().unwrap();
    assert!(verify_backup_password(&backup, Some(MASTER)));
    assert!(!verify_backup_password(&backup, Some("wrong")));

    let mut target = fast(temp_storage("backup-target"));
    target.restore_backup(&backup, Some(MASTER), None).unwrap();
    let mut titles: Vec<String> = target
        .items()
        .unwrap()
        .iter()
        .map(|i| i.title.clone())
        .collect();
    titles.sort();
    assert_eq!(titles, vec!["One", "Two"]);

    // A backup re-keyed on restore must still unlock with the new password.
    let mut third = fast(temp_storage("backup-rekeyed"));
    third
        .restore_backup(&backup, Some(MASTER), Some("totally different master"))
        .unwrap();
    assert!(third.export_backup().unwrap().header.iterations.is_some());
    assert_eq!(third.items().unwrap().len(), 2);
    third.lock();
    assert!(third.unlock("totally different master").unwrap());
}

#[test]
fn a_passwordless_backup_restores_without_a_password() {
    let mut source = fast(temp_storage("backup-device"));
    source.create(None).unwrap();
    source
        .add_item(&json!({ "title": "Solo", "password": "alpha" }))
        .unwrap();
    let backup = source.export_backup().unwrap();
    assert_eq!(
        parse_backup(&serialize_backup(&backup).unwrap())
            .unwrap()
            .header
            .protection,
        Some(VaultProtection::Device)
    );

    // Any password must still verify, because none is required.
    assert!(verify_backup_password(&backup, None));
    assert!(verify_backup_password(&backup, Some("irrelevant")));

    let mut target = fast(temp_storage("backup-device-target"));
    target.restore_backup(&backup, None, None).unwrap();
    assert_eq!(target.items().unwrap()[0].title, "Solo");

    // Restoring it passwordless explicitly is also possible.
    let mut third = fast(temp_storage("backup-device-third"));
    third.restore_backup(&backup, None, Some("")).unwrap();
    assert_eq!(third.protection().unwrap(), Some(VaultProtection::Device));
    assert_eq!(third.items().unwrap()[0].password, "alpha");
}

#[test]
fn an_export_can_leave_the_settings_behind() {
    let mut source = fast(temp_storage("backup-settings"));
    source.create(None).unwrap();
    source
        .add_item(&json!({ "title": "One", "password": "alpha" }))
        .unwrap();
    source
        .save_preferences(json!({ "theme": "dark", "accent": "clay" }))
        .unwrap();

    // With the settings travelling, the blob is in the file and carries the
    // document's own preferences.
    let with = source.export_backup_json_with(true, None).unwrap();
    assert!(with.contains("\"preferences\""));
    assert!(with.contains("\"theme\": \"dark\""));
    // The plain export is the same file: the switch defaults to on, so the
    // no-argument call carries the blob too. (Only `exportedAt` can differ
    // between the two calls, which is why this reads the key and not the
    // whole string.)
    assert!(source.export_backup_json().unwrap().contains("\"preferences\""));

    // Without them the key is absent entirely -- not null, not empty. That is
    // the file the web build writes, and its `parseBackup` never looks for it.
    let without = source.export_backup_json_with(false, None).unwrap();
    assert!(!without.contains("preferences"));

    // A file with no blob restores the vault over this device's own settings
    // rather than replacing them...
    let mut target = fast(temp_storage("backup-settings-target"));
    target.create(None).unwrap();
    target
        .save_preferences(json!({ "theme": "light", "accent": "sage" }))
        .unwrap();
    let stripped = parse_backup(&without).unwrap();
    assert!(stripped.preferences.is_none());
    target.restore_backup(&stripped, None, None).unwrap();
    assert_eq!(
        target.preferences().get("theme").and_then(|v| v.as_str()),
        Some("light")
    );
    assert_eq!(target.items().unwrap()[0].title, "One");

    // ...and one with the blob replaces them, which is the point of the switch.
    let full = parse_backup(&with).unwrap();
    target.restore_backup(&full, None, None).unwrap();
    assert_eq!(
        target.preferences().get("theme").and_then(|v| v.as_str()),
        Some("dark")
    );
}

#[test]
fn a_protected_export_unlocks_with_the_export_password_alone() {
    let mut source = fast(temp_storage("backup-protected-export"));
    source.create(None).unwrap();
    source
        .add_item(&json!({ "title": "Wrapped", "password": "alpha" }))
        .unwrap();

    let text = source
        .export_backup_json_with_password("export passphrase")
        .unwrap();
    let backup = parse_backup(&text).unwrap();
    assert_eq!(backup.header.protection, Some(VaultProtection::Password));
    assert!(verify_backup_password(&backup, Some("export passphrase")));
    assert!(!verify_backup_password(&backup, Some("wrong")));

    // The item ciphertexts survive the re-wrap and the file installs
    // elsewhere under its own password.
    let mut target = fast(temp_storage("backup-protected-export-target"));
    target
        .restore_backup(&backup, Some("export passphrase"), None)
        .unwrap();
    assert_eq!(target.items().unwrap()[0].password, "alpha");
}

