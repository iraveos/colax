//! Engine suite: the vault-service cases from `lite version/test/crypto.test.ts`
//! ported to Rust, plus file persistence and TS-fixture compatibility checks.
//!
//! PBKDF2 stays fast by dropping `kdf_iterations` to 1000 in tests; the one
//! test that must use the production cost is the TS fixture restore, which
//! derives at the header's own 600 000 iterations (proving the real path).

use std::thread;
use std::time::Duration;

use colax_core::{
    parse_backup, serialize_backup, verify_backup_password, StoredItem, VaultEngine, VaultError,
    VaultProtection, VaultStorage, BACKUP_FORMAT, PBKDF2_ITERATIONS,
};
use serde_json::json;

/// Fixture key, not a credential — see the note on crypto.rs's copy of it.
/// Generated by `scripts/make-ts-fixture.mjs`, which is also what writes the
/// TS backup the cross-compatibility test restores.
const MASTER: &str = "colax-lite-fixture-key-v1";

/// Fresh, empty vault path for one test.
fn temp_storage(tag: &str) -> VaultStorage {
    let dir = std::env::temp_dir().join(format!("colax-engine-{}-{tag}", std::process::id()));
    let _ = std::fs::create_dir_all(&dir);
    let path = dir.join("vault.json");
    let _ = std::fs::remove_file(&path);
    VaultStorage::new(path)
}

/// Engine with a cheap KDF; reads still honour whatever the header says.
fn fast(storage: VaultStorage) -> VaultEngine {
    let mut engine = VaultEngine::open(storage).unwrap();
    engine.kdf_iterations = 1000;
    engine
}

/* ---- Ported from crypto.test.ts: optional vault password --------------- */

#[test]
fn passwordless_create_open_and_add_a_password_later() {
    let mut vault = fast(temp_storage("passwordless"));

    vault.create(None).unwrap();
    assert_eq!(vault.protection().unwrap(), Some(VaultProtection::Device));

    let item = vault
        .add_item(&json!({
            "title": "Bank",
            "username": "me@example.com",
            "password": "secret-value",
        }))
        .unwrap();
    vault.lock();
    assert!(vault.unlock("").unwrap(), "opens with no password at all");
    let items = vault.items().unwrap();
    assert_eq!(items[0].password, "secret-value");

    // Enabling a password must not disturb existing ciphertexts.
    vault.enable_password(MASTER).unwrap();
    assert_eq!(vault.protection().unwrap(), Some(VaultProtection::Password));
    vault.lock();

    assert!(
        !vault.unlock("").unwrap(),
        "an empty password no longer works"
    );
    assert!(vault.unlock(MASTER).unwrap());
    let items = vault.items().unwrap();
    assert_eq!(items[0].password, "secret-value");
    assert_eq!(items[0].id, item.id);
}

#[test]
fn removing_the_password_requires_the_current_one() {
    let mut vault = fast(temp_storage("disable-password"));
    vault.create(Some(MASTER)).unwrap();
    vault
        .add_item(&json!({ "title": "GitHub", "password": "keep-me" }))
        .unwrap();

    let err = vault.disable_password("wrong password").unwrap_err();
    assert!(matches!(err, VaultError::Auth), "got {err:?}");
    assert_eq!(
        vault.protection().unwrap(),
        Some(VaultProtection::Password),
        "still protected after a failed attempt"
    );

    vault.disable_password(MASTER).unwrap();
    assert_eq!(vault.protection().unwrap(), Some(VaultProtection::Device));

    vault.lock();
    assert!(vault.unlock("").unwrap());
    assert_eq!(vault.items().unwrap()[0].password, "keep-me");
}

