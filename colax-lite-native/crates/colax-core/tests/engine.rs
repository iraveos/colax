#[test]
fn changing_the_password_rewraps_only_the_header() {
    let mut vault = fast(temp_storage("change-password"));
    vault.create(Some(MASTER)).unwrap();
    vault
        .add_item(&json!({ "title": "GitHub", "password": "example-value" }))
        .unwrap();

    let blob_before = {
        let doc = vault.export_backup().unwrap();
        doc.items[0].blob.clone()
    };

    vault
        .change_master_password(MASTER, "a brand new master password")
        .unwrap();
    vault.lock();
    assert!(!vault.unlock(MASTER).unwrap());
    assert!(vault.unlock("a brand new master password").unwrap());
    assert_eq!(vault.items().unwrap()[0].password, "example-value");

    // The item ciphertext is untouched: the vault key itself never changed.
    let blob_after = vault.export_backup().unwrap().items[0].blob.clone();
    assert_eq!(blob_before, blob_after, "rewrap must not re-encrypt items");
}

